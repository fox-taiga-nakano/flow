import { cliNotes, helpOption } from './cli-notes.mjs'
import { plainOutput } from './terminal.mjs'

export const generated = '<!-- Generated by pnpm docs:generate. -->'
const fence = (kind, value) => '````' + kind + '\n' + value + '\n````'
const inline = (text) => '`' + text + '`'
const route = (id) => '/reference/cli/' + (id === 'flow' ? '' : id + '/')
const markdown = (title, description, body) =>
    `---\ntitle: ${JSON.stringify(title)}\ndescription: ${JSON.stringify(description)}\n---\n\n${generated}\n\n${body.trim()}\n`

export function references(commands, demo) {
    const byId = new Map(commands.map((command) => [command.id, command]))
    for (const id of Object.keys(cliNotes)) {
        if (!byId.has(id)) {
            throw new Error(`cli-notes.mjs: 削除されたコマンド ${id}`)
        }
    }
    return commands.map((command) => {
        const { id, name, summary, syntax, args, options } = command
        const manual = cliNotes[id]
        if (!manual) {
            throw new Error(`cli-notes.mjs: ${id} の解説がありません`)
        }
        const validate = (kind, entries, names) => {
            for (const key of names) {
                if (!entries[key]?.trim()) {
                    throw new Error(`cli-notes.mjs: ${id} ${kind} ${key} の詳細説明がありません`)
                }
            }
            for (const key of Object.keys(entries)) {
                if (!names.includes(key)) {
                    throw new Error(`cli-notes.mjs: ${id} ${kind} ${key} は CLI から削除されました`)
                }
            }
        }
        validate(
            '引数',
            manual.args,
            args.map((arg) => arg.name)
        )
        validate(
            'オプション',
            manual.options,
            options.map((opt) => opt.id).filter((key) => key !== '--help')
        )
        if (!byId.has(manual.related)) {
            throw new Error(`cli-notes.mjs: ${id} の関連先 ${manual.related} が存在しません`)
        }
        const children = commands.filter(
            (candidate) =>
                candidate.id !== 'flow' && candidate.id.split('/').slice(0, -1).join('/') === (id === 'flow' ? '' : id)
        )
        const descendants = children.length
            ? '\n## サブコマンド\n\n' +
              children.map((child) => `- [${inline(child.name)}](${route(child.id)}) — ${child.summary}`).join('\n')
            : ''
        const scene = typeof manual.output === 'object' && manual.output.scene
        const output = scene
            ? plainOutput(scene === 'approval' ? demo.approval.ansi : demo.scenes.find((s) => s.id === scene).ansi)
            : manual.output
        const renderedArgs = args
            .map(
                (arg) =>
                    `### ${inline(arg.name)}\n\n${arg.required ? '必須' : '省略可'}。${arg.variadic ? '複数指定可。' : ''}${arg.default === undefined ? '' : `既定値は ${inline(JSON.stringify(arg.default))}。 `}${arg.choices ? `選択肢は ${arg.choices.map(inline).join('、')}。 ` : ''}${manual.args[arg.name]}`
            )
            .join('\n\n')
        const renderedOptions = options
            .map((option) => {
                const metadata = [
                    option.kind === 'flag' ? 'フラグ' : '値を指定',
                    option.required ? '必須' : '省略可',
                    option.default === undefined ? '' : `既定値 ${inline(JSON.stringify(option.default))}`,
                    option.choices?.length ? `CLI が受け付ける値 ${option.choices.map(inline).join('、')}` : '',
                ]
                    .filter(Boolean)
                    .join(' · ')
                const detail =
                    option.id === '--help'
                        ? `${helpOption} 例は ${inline(name + ' --help')}。`
                        : manual.options[option.id]
                return `### ${inline(option.flags)}\n\n${metadata}\n\n${detail}`
            })
            .join('\n\n')
        return [
            id === 'flow' ? 'index.md' : `${id}.md`,
            markdown(
                name,
                summary,
                `
${summary}。${manual.use}

## 構文

${fence('bash', syntax)}
${command.aliases.length ? '\n別名は ' + command.aliases.map(inline).join('、') + '。' : ''}
${descendants}
## 引数

${renderedArgs || '位置引数はありません。'}

## オプション

${renderedOptions || '専用のオプションはありません。'}

${id !== 'flow' ? `対象プロジェクトを切り替えるには [共通オプション](${route('flow')}) の ${inline('--project')} をサブコマンドの前に指定します。\n` : ''}
## 実行例

${fence('bash', manual.example)}

${manual.use}

### 出力例

${fence('text', output)}

## 実行時の影響

${manual.effects}

## 関連コマンド

- [${byId.get(manual.related).name}](${route(manual.related)})
`
            ),
        ]
    })
}

export function configReferences(config) {
    const sections = Map.groupBy(config.fields, (field) => {
        const root = field.path.split('.')[0]
        return root === 'version' || root === 'timezone' ? '基本設定' : root
    })
    const settings = ['基本設定', ...[...sections.keys()].filter((key) => key !== '基本設定')]
        .map((key) => {
            const fields = sections.get(key).map((field) => {
                const required = !field.required ? '省略可' : field.ancestorsRequired ? '必須' : '親の指定時に必須'
                return `| ${inline(field.path)} | ${inline(field.type)} | ${required} |`
            })
            return [
                `## ${key === '基本設定' ? key : inline(key)}`,
                '',
                '| 設定キー | 定義型 | 指定 |',
                '| --- | --- | --- |',
                ...fields,
            ].join('\n')
        })
        .join('\n\n')
    return [
        [
            'workflow-schema.md',
            markdown(
                'Workflow 設定項目一覧',
                '型と検証規則から生成した設定リファレンス',
                `
[WORKFLOW.md の設定方法](/reference/workflow/)とあわせて使用します。\`*\` は任意のキーです。「必須」は型定義での指定要否です。\`runner.close_on_complete\` のようにパーサーが既定値を補う項目や、別項目との組み合わせが必要な項目があります。

${settings}

## 検証条件

実際の検証コードから抽出した条件と診断です。[設定方法](/reference/workflow/)に主な条件と実行時の契約をまとめています。

<details>
<summary>パーサーの検証条件</summary>

${fence('typescript', config.validation.map(([condition, error]) => `need(${condition}, ${error})`).join('\n'))}

</details>
`
            ),
        ],
        [
            'worktree-schema.md',
            markdown(
                'worktree 設定の検証規則',
                '同梱テンプレートとシェルのバリデータから生成',
                `
[worktree の設定方法](/reference/worktree/)とあわせて使用します。

## 同梱の設定例

${fence('json', JSON.stringify(config.worktreeExample, null, 2))}

利用可能なフックは ${config.hooks.map(inline).join('、')} です。

## 検証処理

${fence('text', config.worktreeValidation)}
`
            ),
        ],
    ]
}
